#!/usr/bin/env node
// Builds src/generated/api-actions.ts from the installed `bundlesocial` SDK: one entry per SDK method,
// with its HTTP method, path, summary and parameters. Run after bumping the SDK: `npm run generate:actions`.
// The CLI keeps a byte-identical copy (same script, same SDK version).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const ts = require("typescript");

const root = process.cwd();
const sdkDir = path.join(root, "node_modules/bundlesocial");
const sdkVersion = JSON.parse(fs.readFileSync(path.join(sdkDir, "package.json"), "utf8")).version;
const dtsPath = path.join(sdkDir, "dist/index.d.ts");
const jsSource = fs.readFileSync(path.join(sdkDir, "dist/index.js"), "utf8");
const outPath = path.join(root, process.argv[2] ?? "src/generated/api-actions.ts");

// Parent pointers are needed for JSDoc lookups.
const source = ts.createSourceFile(dtsPath, fs.readFileSync(dtsPath, "utf8"), ts.ScriptTarget.Latest, true);

const typeAliases = new Map();
const services = [];
ts.forEachChild(source, (node) => {
  if (ts.isTypeAliasDeclaration(node)) typeAliases.set(node.name.text, node);
  if (ts.isClassDeclaration(node) && node.name?.text.endsWith("Service")) services.push(node);
});

const docOf = (node) =>
  ts
    .getJSDocCommentsAndTags(node)
    .filter(ts.isJSDoc)
    .map((d) => (typeof d.comment === "string" ? d.comment : ts.getTextOfJSDocComment(d.comment) ?? ""))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();

const clip = (text, max) => (text.length > max ? `${text.slice(0, max - 1)}…` : text);

function fieldsOf(typeLiteral) {
  return typeLiteral.members.filter(ts.isPropertySignature).map((member) => ({
    name: member.name.getText(source).replace(/['"]/g, ""),
    required: !member.questionToken,
    type: clip(member.type ? member.type.getText(source).replace(/\s+/g, " ") : "unknown", 160),
    doc: clip(docOf(member), 200),
  }));
}

// HTTP method, URL and transport shape come from the compiled request calls.
function requestShape(methodName) {
  const start = jsSource.indexOf(`${methodName}(`);
  if (start < 0) return null;
  const body = jsSource.slice(start, start + 600);
  const method = body.match(/method:"([A-Z]+)"/)?.[1];
  const url = body.match(/url:"([^"]+)"/)?.[1];
  return { method, url, formData: body.includes("formData:") };
}

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const actions = [];
for (const service of services) {
  const serviceName = service.name.text.replace(/Service$/, "");
  const prefix = serviceName.charAt(0).toLowerCase() + serviceName.slice(1);
  for (const member of service.members) {
    if (!ts.isMethodDeclaration(member) || !member.name) continue;
    const methodName = member.name.getText(source);
    const shape = requestShape(methodName);
    if (!shape?.method || shape.formData) continue; // file uploads need multipart bodies, not JSON

    const jsDoc = ts.getJSDocCommentsAndTags(member).filter(ts.isJSDoc)[0];
    const lines = (typeof jsDoc?.comment === "string" ? jsDoc.comment : ts.getTextOfJSDocComment(jsDoc?.comment) ?? "")
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean);

    const dataTypeName = `${methodName.charAt(0).toUpperCase()}${methodName.slice(1)}Data`;
    const alias = typeAliases.get(dataTypeName);
    let params = [];
    let body = [];
    if (alias && ts.isTypeLiteralNode(alias.type)) {
      for (const field of fieldsOf(alias.type)) {
        if (field.name === "requestBody") {
          const member = alias.type.members.find((m) => m.name?.getText(source) === "requestBody");
          if (member?.type && ts.isTypeLiteralNode(member.type)) body = fieldsOf(member.type);
          else body = [{ name: "*", required: false, type: clip(member?.type?.getText(source) ?? "object", 160), doc: "Request body" }];
        } else {
          params.push(field);
        }
      }
    }

    const rest = methodName.startsWith(prefix) ? methodName.slice(prefix.length) : methodName;
    actions.push({
      id: `${kebab(prefix)}.${kebab(rest.charAt(0).toLowerCase() + rest.slice(1))}`,
      sdk: [prefix, methodName],
      http: `${shape.method} ${shape.url}`,
      readOnly: shape.method === "GET",
      summary: clip(lines[0] ?? methodName, 160),
      description: clip(lines.slice(1).join(" "), 400),
      params,
      body,
    });
  }
}
actions.sort((a, b) => a.id.localeCompare(b.id));

const header = `// GENERATED by scripts/generate-api-actions.mjs from bundlesocial@${sdkVersion}. Do not edit by hand.
// Every JSON endpoint of the public API, so agents can reach what no dedicated tool covers.

export interface ApiActionField {
  name: string;
  required: boolean;
  type: string;
  doc: string;
}

export interface ApiAction {
  /** Stable id: "<sdk service>.<operation>" in kebab case, e.g. "misc.youtube-edit-video". */
  id: string;
  /** [service, method] on the bundlesocial SDK client. */
  sdk: [string, string];
  http: string;
  readOnly: boolean;
  summary: string;
  description: string;
  /** Path and query parameters, passed at the top level of the SDK call. */
  params: ApiActionField[];
  /** JSON body fields, passed as requestBody. "*" means a free-form body. */
  body: ApiActionField[];
}

export const API_SDK_VERSION = ${JSON.stringify(sdkVersion)};

export const API_ACTIONS: ApiAction[] = `;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${header}${JSON.stringify(actions, null, 2)};\n`);
console.log(`wrote ${actions.length} actions to ${path.relative(root, outPath)} (bundlesocial@${sdkVersion})`);
